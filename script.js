function applyLanguage(lang) {
  const dict = translations[lang] || translations.fr;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dict[key]) node.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    const key = node.dataset.i18nHtml;
    if (dict[key]) node.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (dict[key]) node.placeholder = dict[key];
  });

  document.querySelectorAll(".lang-btn").forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  document.querySelectorAll(".lang-select").forEach((select) => {
    select.value = lang;
  });

  document.querySelectorAll("[data-fr-only]").forEach((row) => {
    row.hidden = lang === "en";
  });

  styleBrandNameMarks(document.body);
  localStorage.setItem("styleme-language", lang);
}

function initLanguageSelects() {
  document.querySelectorAll(".lang-switch").forEach((switcher) => {
    if (switcher.nextElementSibling?.classList.contains("lang-select")) return;
    const select = document.createElement("select");
    select.className = "lang-select";
    select.setAttribute("aria-label", switcher.getAttribute("aria-label") || "Changer la langue");
    Object.entries(languageLabels).forEach(([value, label]) => {
      const option = document.createElement("option");
      option.value = value;
      option.textContent = label;
      select.appendChild(option);
    });
    switcher.insertAdjacentElement("afterend", select);
  });
}

function styleBrandNameMarks(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue.includes("Styleme.fr")) return NodeFilter.FILTER_REJECT;
      const parent = node.parentElement;
      if (!parent || parent.closest(".site-name")) return NodeFilter.FILTER_REJECT;
      if (["SCRIPT", "STYLE", "TEXTAREA", "INPUT"].includes(parent.tagName)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });

  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    const fragment = document.createDocumentFragment();
    const parts = node.nodeValue.split("Styleme.fr");
    parts.forEach((part, index) => {
      if (part) fragment.appendChild(document.createTextNode(part));
      if (index < parts.length - 1) {
        const mark = document.createElement("span");
        mark.className = "site-name";
        mark.textContent = "Styleme.fr";
        fragment.appendChild(mark);
      }
    });
    node.parentNode.replaceChild(fragment, node);
  });
}

